//! Generates NVENC's FFI bindings for `couch-codec-nvenc` (M12d) from the
//! vendored `third_party/nv-codec-headers/nvEncodeAPI.h`: the SDK 13.0 header
//! FFmpeg's pinned build compiles against. Run once after changing that
//! header; normal builds need no libclang.
//!
//! The header is parsed for Windows' layout with `_WIN32` undefined, so it
//! declares its own `GUID` and `NVENC_RECT` rather than pulling in
//! `windows.h`; on x86-64 its `__stdcall` is the C convention anyway. Its
//! struct versions are function-like macros and its GUIDs `static const`
//! variables, which bindgen leaves out: `couch-codec-nvenc`'s `api` module
//! writes those it uses.

use std::{fs, path::Path};

use anyhow::{Context, anyhow, bail};

use crate::deps;

/// The vendored header, relative to the repository root.
pub(crate) const HEADER: &str = "third_party/nv-codec-headers/nvEncodeAPI.h";
/// Its SHA-256, as its README names it.
pub(crate) const HEADER_SHA256: &str =
    "4fe4094541ef0f8a13249d97a8692dc5f835a6e9dd42eeadb3e2f7321d54dc7e";
/// Where the bindings go.
pub(crate) const BINDING_FILE: &str =
    "crates/couch-codec-nvenc/bindings/nvenc-x86_64-pc-windows-msvc.rs";

/// The provenance line written at the top of the bindings.
pub(crate) fn provenance(sha256: &str) -> String {
    format!("// nvEncodeAPI.h sha256: {sha256}")
}

pub(crate) fn generate(root: &Path) -> anyhow::Result<()> {
    let header = root.join(HEADER);
    let sha = deps::sha256_file(&header).with_context(|| format!("reading {HEADER}"))?;
    if sha != HEADER_SHA256 {
        bail!(
            "{HEADER} isn't the pinned header (sha256 {sha}); update HEADER_SHA256 and its README with it"
        );
    }
    let bindings = bindgen::builder()
        .raw_line("// Generated by `cargo xtask gen-nvenc-bindings`. Do not edit.")
        .raw_line("// NVIDIA Video Codec SDK 13.0's nvEncodeAPI.h (MIT), from nv-codec-headers.")
        .raw_line(provenance(&sha))
        .rust_target(bindgen::RustTarget::stable(68, 0).map_err(|e| anyhow!("{e}"))?)
        .clang_arg("--target=x86_64-pc-windows-msvc")
        .clang_arg("-U_WIN32")
        .header(header.to_string_lossy())
        .allowlist_type("_?NV_.*|_?NVENC.*|PNVENC.*|_?GUID")
        .allowlist_var("NVENCAPI_.*|NVENC_.*|NV_ENC_.*|NV_MAX_.*")
        // NvEncodeAPICreateInstance and NvEncodeAPIGetMaxSupportedVersion are
        // loaded from the driver's DLL, never linked: no functions bound.
        // `static const GUID`s: no symbol to link; written by hand.
        .blocklist_item("NV_ENC_.*_GUID")
        .prepend_enum_name(false)
        .derive_default(true)
        .layout_tests(true)
        .generate()
        .context("bindgen failed; is LLVM installed and LIBCLANG_PATH set?")?;
    let out = root.join(BINDING_FILE);
    fs::create_dir_all(out.parent().expect("binding file has a parent"))?;
    bindings.write_to_file(&out)?;
    let text = fs::read_to_string(&out)?;
    for needed in [
        "pub struct _NV_ENCODE_API_FUNCTION_LIST",
        "pub struct _NV_ENC_PIC_PARAMS",
        "pub struct _NV_ENC_CONFIG_H264",
        "pub struct _GUID",
    ] {
        if !text.contains(needed) {
            bail!("the bindings lack `{needed}`; check the allowlist");
        }
    }
    println!("wrote {} ({} KiB)", out.display(), text.len() / 1024);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> &'static Path {
        Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap()
    }

    /// The committed bindings come from the vendored header, and the header
    /// is the one its README names.
    #[test]
    fn the_nvenc_bindings_match_the_vendored_header() {
        let root = root();
        let sha = deps::sha256_file(&root.join(HEADER)).unwrap();
        assert_eq!(sha, HEADER_SHA256, "{HEADER} changed");
        let readme =
            fs::read_to_string(root.join("third_party/nv-codec-headers/README.md")).unwrap();
        assert!(
            readme.contains(HEADER_SHA256),
            "the README names another header"
        );
        let bindings = fs::read_to_string(root.join(BINDING_FILE)).unwrap();
        assert!(
            bindings.contains(&provenance(HEADER_SHA256)),
            "{BINDING_FILE} wasn't generated from this header: run `cargo xtask gen-nvenc-bindings`"
        );
    }
}
